export function t(language, key) {
  const pack = COPY[language] || COPY.en
  return pack[key] ?? COPY.en[key] ?? key
}

export function modeLabel(language, modeId, fallback) {
  const map = {
    rodin: 'hyper3d',
    auto: 'auto',
    tripo: 'tripo',
    fal: 'fal',
    hunyuan: 'hunyuan',
    'hunyuan-sketch': 'hunyuanSketch',
    cinematic: 'jsDepth',
    local: 'localGlb',
  }
  const key = map[modeId]
  return (key && t(language, key)) || fallback || modeId
}
